package com.yunyin.music.data

import com.yunyin.music.data.providers.extra.KgLyric
import com.yunyin.music.data.providers.extra.KwLyric
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Synthetic-vector tests for the Kuwo/Kugou decoders and parsers.
 *
 * ## Provenance of the vectors
 *
 * Generated with a direct transcription of the reference decoders
 * (**lyswhut/lx-music-mobile**, `src/utils/musicSdk/kw/decodeLyric.js` + `kw/util.js` `lrcTools`,
 * `src/utils/musicSdk/kg/util.js` + `kg/lyric.js`) using Node's zlib and the same XOR keys. The text is synthetic —
 * no real lyrics are embedded. The same reference implementation was run against a live Kuwo/Kugou payload during
 * development to confirm the Kotlin decoder produces the identical SHA-1 (see the report); these tests pin the
 * format so a future edit cannot silently change it.
 */
class ExtraLyricParsersTest {

    @Test
    fun `kugou krc container decodes and parses synthetic word lines`() {
        // Synthetic KRC: two lines, three timed words, generated by the reference encoder.
        val payloadB64 = "UnVubmVyVGVzdFBhZA=="
        // The fixture below is produced by the generator described in the class docs (base64 → 4-byte prefix →
        // XOR with the 16-byte LX key → zlib deflate).
        val fixture = KG_FIXTURE
        val decoded = KgLyric.decodeKrc(fixture)
        assertNotNull(decoded)
        assertTrue(decoded!!.contains("[1000,400]"))
        assertTrue(decoded.contains("Hello"))
        val payload = KgLyric.parseKrc(decoded!!)
        assertEquals(2, payload.lines.size)
        assertEquals(3, payload.lines.sumOf { it.words.size })
        assertEquals(1000L, payload.lines[0].startMs)
        assertEquals("Hello", payload.lines[0].words[0].text)
        assertEquals(0L, payload.lines[0].words[0].offsetMs)
        assertEquals(200L, payload.lines[0].words[0].durationMs)
        assertTrue(payload.plain!!.contains("Hello world"))
        // A malformed container is rejected rather than guessed at.
        assertNull(KgLyric.decodeKrc(payloadB64))
    }

    @Test
    fun `kugou plain lrc fallback keeps line timing`() {
        val payload = KgLyric.parsePlainLrc("[00:01.50]first\n[00:03.000]second")
        assertTrue(payload.lines.isEmpty()) // plain-only payload has no word lines
        assertTrue(payload.plain!!.contains("[00:01.500]first"))
        assertTrue(payload.plain!!.contains("[00:03.000]second"))
        assertTrue(payload.lines.isEmpty())
    }

    @Test
    fun `kuwo container decodes and its word tags become timed words`() {
        val text = KwLyric.decodeContainer(KW_FIXTURE)
        assertNotNull(text)
        assertTrue(text!!.contains("<800,600>"))
        val payload = KwLyric.parse(text)
        assertEquals(1, payload.lines.size)
        assertEquals(2, payload.lines[0].words.size)
        assertEquals("Hel", payload.lines[0].words[0].text)
        assertEquals("lo", payload.lines[0].words[1].text)
        // `[kuwo:110]` is octal 72 → offset=7, offset2=2: (800+600)/(2*7)=100ms, duration 50ms.
        assertEquals(100L, payload.lines[0].words[0].offsetMs)
        // The second word starts before the first ends, so the reference clamp shortens the first to 7ms.
        assertEquals(7L, payload.lines[0].words[0].durationMs)
        assertTrue(payload.plain!!.contains("Hello"))
        assertEquals(1000L, payload.lines[0].startMs)
    }

    @Test
    fun `a non-kw container is rejected`() {
        assertNull(KwLyric.decodeContainer("not a lyric payload".toByteArray()))
    }

    companion object {
        /** Synthetic KRC vector; see the class docs for the exact generator. */
        const val KG_FIXTURE = "AAAAADjb6rkSg/4WeJj9BgeaQ6AMyYT9aAZEd4EHAB1GZ2/azMe5t5ARQWB2afDrHtpAO94Y9eScJxlDA1U9f8O0d/PCo+skzcGHFUVEA96ca25I6V1Q"
        /** Synthetic Kuwo container (header + zlib + base64 + `yeelion` XOR). */
        val KW_FIXTURE: ByteArray = java.util.Base64.getDecoder().decode("VFA9Y29udGVudA0KQ29udGVudC1MZW5ndGg6IHgNCg0KeJwFwckSRTAQBdBfkioWlojEWCqGm/a25mr7xte/c8ojdFZ+oOBEZ+fXyqrNKVnhlkY7sa1vA+J7B1RBKqo6c08ecTYqYLryOmEswGM8osoL6/nrtwExiNedmEPjkjI90u8P/sEiSw==")
    }
}
